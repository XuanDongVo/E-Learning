
CREATE TABLE assessment_attempt_answer_mutations (
                                                     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                                     attempt_id BIGINT NOT NULL,
                                                     attempt_question_id BIGINT NOT NULL,

                                                     request_id UUID NOT NULL,
                                                     payload_hash VARCHAR(64) NOT NULL,

                                                     result_revision BIGINT NOT NULL,
                                                     saved_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,

                                                     CONSTRAINT fk_answer_mutation_attempt
                                                         FOREIGN KEY (attempt_id)
                                                             REFERENCES assessment_attempts (id),

                                                     CONSTRAINT fk_answer_mutation_attempt_question
                                                         FOREIGN KEY (attempt_question_id)
                                                             REFERENCES assessment_attempt_questions (id),

                                                     CONSTRAINT uq_attempt_answer_mutation_request
                                                         UNIQUE (attempt_id, request_id),

                                                     CONSTRAINT ck_answer_mutation_revision
                                                         CHECK (result_revision > 0),

                                                     CONSTRAINT ck_answer_mutation_payload_hash
                                                         CHECK (length(payload_hash) = 64)
);

CREATE INDEX ix_attempt_answer_mutation_question
    ON assessment_attempt_answer_mutations (attempt_question_id);
