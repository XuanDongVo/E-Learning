-- Assignment Composition v1. AssignmentQuestion remains a position-free ownership relation.
-- Existing assignments receive one generated section and ordered question items (question_id ASC).

ALTER TABLE assignments
    ADD COLUMN composition_schema_version INTEGER NOT NULL DEFAULT 1,
    ADD COLUMN composition_provenance VARCHAR(30) NOT NULL DEFAULT 'AUTHOR_CREATED',
    ADD COLUMN show_score_after_submit BOOLEAN NOT NULL DEFAULT TRUE;

ALTER TABLE assignments
    ADD CONSTRAINT ck_assignment_composition_schema_version_positive
        CHECK (composition_schema_version > 0),
    ADD CONSTRAINT ck_assignment_composition_provenance
        CHECK (composition_provenance IN ('AUTHOR_CREATED', 'LEGACY_GENERATED'));

CREATE TABLE assignment_sections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id BIGINT NOT NULL,
    position INTEGER NOT NULL,
    title VARCHAR(200),
    instructions TEXT,
    CONSTRAINT fk_assignment_section_assignment
        FOREIGN KEY (assignment_id) REFERENCES assignments(id) ON DELETE CASCADE,
    CONSTRAINT ck_assignment_section_position_positive CHECK (position > 0),
    CONSTRAINT uq_assignment_section_position UNIQUE (assignment_id, position),
    CONSTRAINT uq_assignment_section_id_assignment UNIQUE (id, assignment_id)
);

CREATE TABLE assignment_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id BIGINT NOT NULL,
    section_id BIGINT NOT NULL,
    parent_item_id BIGINT,
    position INTEGER NOT NULL,
    item_type VARCHAR(20) NOT NULL,
    question_id BIGINT,
    possible_points NUMERIC(8, 2) NOT NULL DEFAULT 0,
    is_required BOOLEAN NOT NULL DEFAULT TRUE,
    is_example BOOLEAN NOT NULL DEFAULT FALSE,
    block_payload JSONB,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_assignment_item_assignment
        FOREIGN KEY (assignment_id) REFERENCES assignments(id) ON DELETE CASCADE,
    CONSTRAINT fk_assignment_item_section
        FOREIGN KEY (section_id, assignment_id)
        REFERENCES assignment_sections(id, assignment_id) ON DELETE CASCADE,
    CONSTRAINT uq_assignment_item_parent_scope UNIQUE (id, assignment_id, section_id),
    CONSTRAINT fk_assignment_item_parent
        FOREIGN KEY (parent_item_id, assignment_id, section_id)
        REFERENCES assignment_items(id, assignment_id, section_id) ON DELETE CASCADE,
    CONSTRAINT fk_assignment_item_question
        FOREIGN KEY (question_id) REFERENCES assignment_questions(question_id) ON DELETE CASCADE,
    CONSTRAINT ck_assignment_item_position_positive CHECK (position > 0),
    CONSTRAINT ck_assignment_item_type
        CHECK (item_type IN ('QUESTION', 'INSTRUCTIONS', 'PASSAGE', 'MEDIA', 'POOL')),
    CONSTRAINT ck_assignment_item_points_non_negative CHECK (possible_points >= 0),
    CONSTRAINT ck_assignment_item_question_shape CHECK (
        (item_type = 'QUESTION' AND question_id IS NOT NULL AND block_payload IS NULL)
        OR
        (item_type <> 'QUESTION' AND question_id IS NULL AND block_payload IS NOT NULL)
    ),
    CONSTRAINT ck_assignment_item_example_points CHECK (NOT is_example OR possible_points = 0)
);

CREATE UNIQUE INDEX uq_assignment_item_root_position
    ON assignment_items(section_id, position) WHERE parent_item_id IS NULL;
CREATE UNIQUE INDEX uq_assignment_item_child_position
    ON assignment_items(parent_item_id, position) WHERE parent_item_id IS NOT NULL;
CREATE UNIQUE INDEX uq_assignment_item_question
    ON assignment_items(assignment_id, question_id) WHERE question_id IS NOT NULL;
CREATE INDEX idx_assignment_items_assignment_order
    ON assignment_items(assignment_id, section_id, parent_item_id, position);

-- Deterministic, explicitly labelled legacy composition. Do not fabricate historical blocks/groups.
INSERT INTO assignment_sections (assignment_id, position, title, instructions)
SELECT a.id, 1, 'Section 1', NULL
FROM assignments a
WHERE NOT EXISTS (
    SELECT 1 FROM assignment_sections s WHERE s.assignment_id = a.id
);

INSERT INTO assignment_items (
    assignment_id, section_id, parent_item_id, position, item_type,
    question_id, possible_points, is_required, is_example, block_payload
)
SELECT
    aq.assignment_id,
    s.id,
    NULL,
    ROW_NUMBER() OVER (PARTITION BY aq.assignment_id ORDER BY aq.question_id)::INTEGER,
    'QUESTION',
    aq.question_id,
    1,
    TRUE,
    FALSE,
    NULL
FROM assignment_questions aq
JOIN assignment_sections s ON s.assignment_id = aq.assignment_id AND s.position = 1
WHERE NOT EXISTS (
    SELECT 1 FROM assignment_items i
    WHERE i.assignment_id = aq.assignment_id AND i.question_id = aq.question_id
);

UPDATE assignments
SET composition_provenance = 'LEGACY_GENERATED';
